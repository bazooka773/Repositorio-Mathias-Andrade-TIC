let contador = 10
console.log("Valor inicial:", contador)

// El sufijo devuelve el valor anterior y luego incrementa la variable.
console.log("contador++ devuelve:", contador++)
console.log("Valor después de contador++:", contador)

// El prefijo incrementa primero y devuelve el nuevo valor.
console.log("++contador devuelve:", ++contador)

// El prefijo decrementa primero y devuelve el nuevo valor.
console.log("--contador devuelve:", --contador)

// El sufijo devuelve el valor anterior y luego decrementa la variable.
console.log("contador-- devuelve:", contador--)
console.log("Valor después de contador--:", contador)
