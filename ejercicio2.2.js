let numero1 = 5
let numero2 = 3

console.log("==:", numero1 == numero2)
console.log("===:", numero1 === numero2)
console.log("!=:", numero1 != numero2)
console.log("!==:", numero1 !== numero2)
console.log(">:", numero1 > numero2)
console.log("<:", numero1 < numero2)
console.log(">=:", numero1 >= numero2)
console.log("<=:", numero1 <= numero2)

console.log('5 == "5":', 5 == "5")
console.log('5 === "5":', 5 === "5")
// == convierte tipos antes de comparar; === también compara el tipo y no convierte.
